//! A deliberately small, strongly typed ORM.
//!
//! `lite-orm` is PostgreSQL-first: models are ordinary Rust structs, queries
//! are typed plans, and execution is asynchronous.

extern crate self as lite_orm;

mod database;
mod error;
mod migration;
mod query;
mod tls;
mod value;

pub use database::Database;
pub use error::{Error, Result};
pub use lite_orm_macros::Model;
pub use migration::{Migration, MigrationReport};
pub use query::{Column, CompiledQuery, Delete, Expr, Order, Select, Update};
pub use value::{IntoValue, ToValue, Value};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RelationMetadata {
    pub name: &'static str,
    pub target: &'static str,
    pub fields: &'static [&'static str],
    pub references: &'static [&'static str],
    pub many: bool,
}

/// Types used by generated models, re-exported so generated code needs only
/// the `lite-orm` dependency.
pub mod types {
    pub use chrono::{DateTime, NaiveDate, NaiveDateTime, NaiveTime, Utc};
    pub use serde_json::Value as Json;
    pub use uuid::Uuid;
}

/// The metadata and row mapping generated by `#[derive(Model)]`.
pub trait Model: Sized {
    /// The table backing this model.
    const TABLE: &'static str;
    /// The PostgreSQL schema containing the table.
    const SCHEMA: &'static str = "public";
    /// Columns selected when loading this model, in row-decoding order.
    const COLUMNS: &'static [&'static str];

    #[doc(hidden)]
    fn from_row(row: &tokio_postgres::Row) -> std::result::Result<Self, tokio_postgres::Error>;

    #[doc(hidden)]
    fn insert_columns() -> &'static [&'static str];

    #[doc(hidden)]
    fn insert_values(&self) -> Vec<Value>;

    /// Start a typed `SELECT` for this model.
    fn select() -> Select<Self> {
        Select::new()
    }

    fn update() -> Update<Self> {
        Update::new()
    }

    fn delete() -> Delete<Self> {
        Delete::new()
    }
}

/// Implementation details used by generated code. This is not a stable API.
#[doc(hidden)]
pub mod __private {
    pub use tokio_postgres;
}
