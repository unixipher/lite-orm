use heck::{ToSnakeCase, ToUpperCamelCase};

use crate::schema::{FieldType, Schema};

pub fn rust(schema: &Schema) -> String {
    let mut output =
        String::from("// @generated by liteorm. Do not edit by hand.\n\nuse lite_orm::Model;\n\n");

    for item in &schema.enums {
        let type_name = item.name.to_upper_camel_case();
        output.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]\n");
        output.push_str(&format!("pub enum {type_name} {{\n"));
        for variant in &item.variants {
            let variant_name = rust_variant_name(variant);
            output.push_str(&format!("    {variant_name},\n"));
        }
        output.push_str("}\n\n");

        output.push_str(&format!("impl {type_name} {{\n"));
        output.push_str("    pub fn as_str(&self) -> &'static str {\n");
        output.push_str("        match self {\n");
        for variant in &item.variants {
            let variant_name = rust_variant_name(variant);
            output.push_str(&format!("            {type_name}::{variant_name} => {variant:?},\n"));
        }
        output.push_str("        }\n");
        output.push_str("    }\n");
        output.push_str("}\n\n");

        output.push_str(&format!("impl ::std::fmt::Display for {type_name} {{\n"));
        output.push_str("    fn fmt(&self, f: &mut ::std::fmt::Formatter<'_>) -> ::std::fmt::Result {\n");
        output.push_str("        write!(f, \"{}\", self.as_str())\n");
        output.push_str("    }\n");
        output.push_str("}\n\n");

        output.push_str(&format!("impl ::std::str::FromStr for {type_name} {{\n"));
        output.push_str("    type Err = String;\n");
        output.push_str("    fn from_str(s: &str) -> ::std::result::Result<Self, Self::Err> {\n");
        output.push_str("        match s {\n");
        for variant in &item.variants {
            let variant_name = rust_variant_name(variant);
            output.push_str(&format!("            {variant:?} => Ok({type_name}::{variant_name}),\n"));
        }
        output.push_str(&format!("            _ => Err(format!(\"unknown variant `{{s}}` for {type_name}\")),\n"));
        output.push_str("        }\n");
        output.push_str("    }\n");
        output.push_str("}\n\n");

        output.push_str(&format!("impl ::lite_orm::IntoValue for {type_name} {{\n"));
        output.push_str("    fn into_value(self) -> ::lite_orm::Value {\n");
        output.push_str("        ::lite_orm::Value::Enum(::lite_orm::EnumValue(self.as_str().to_owned()))\n");
        output.push_str("    }\n");
        output.push_str("}\n\n");

        output.push_str(&format!("impl ::lite_orm::ToValue for {type_name} {{\n"));
        output.push_str("    fn to_value(&self) -> ::lite_orm::Value {\n");
        output.push_str("        ::lite_orm::Value::Enum(::lite_orm::EnumValue(self.as_str().to_owned()))\n");
        output.push_str("    }\n");
        output.push_str("}\n\n");

        output.push_str(&format!("impl<'a> ::lite_orm::__private::tokio_postgres::types::FromSql<'a> for {type_name} {{\n"));
        output.push_str("    fn from_sql(_ty: &::lite_orm::__private::tokio_postgres::types::Type, raw: &'a [u8]) -> ::std::result::Result<Self, Box<dyn ::std::error::Error + Sync + Send>> {\n");
        output.push_str("        let s = ::std::str::from_utf8(raw)?;\n");
        output.push_str("        s.parse().map_err(|e: String| e.into())\n");
        output.push_str("    }\n");
        output.push_str("    fn accepts(_ty: &::lite_orm::__private::tokio_postgres::types::Type) -> bool {\n");
        output.push_str("        true\n");
        output.push_str("    }\n");
        output.push_str("}\n\n");

        output.push_str(&format!("impl ::lite_orm::__private::tokio_postgres::types::ToSql for {type_name} {{\n"));
        output.push_str("    fn to_sql(&self, _ty: &::lite_orm::__private::tokio_postgres::types::Type, out: &mut ::lite_orm::__private::bytes::BytesMut) -> ::std::result::Result<::lite_orm::__private::tokio_postgres::types::IsNull, Box<dyn ::std::error::Error + Sync + Send>> {\n");
        output.push_str("        out.extend_from_slice(self.as_str().as_bytes());\n");
        output.push_str("        Ok(::lite_orm::__private::tokio_postgres::types::IsNull::No)\n");
        output.push_str("    }\n");
        output.push_str("    fn accepts(_ty: &::lite_orm::__private::tokio_postgres::types::Type) -> bool {\n");
        output.push_str("        true\n");
        output.push_str("    }\n");
        output.push_str("    ::lite_orm::__private::tokio_postgres::types::to_sql_checked!();\n");
        output.push_str("}\n\n");
    }

    for model in &schema.models {
        output.push_str("#[derive(Debug, Clone, PartialEq, Model)]\n");
        output.push_str(&format!(
            "#[lite_orm(schema = {:?}, table = {:?})]\n",
            model.schema, model.table
        ));
        output.push_str(&format!("pub struct {} {{\n", model.name));
        for field in &model.fields {
            if matches!(field.kind, FieldType::Relation { .. }) {
                continue;
            }
            let rust_name = rust_field_name(&field.name);
            let mut attrs = vec![];
            if field.id {
                attrs.push("primary_key".to_string());
            }
            if field.auto_increment {
                attrs.push("auto_increment".to_string());
            }
            if rust_name != field.column {
                attrs.push(format!("column = {:?}", field.column));
            }
            if !attrs.is_empty() {
                output.push_str(&format!("    #[lite_orm({})]\n", attrs.join(", ")));
            }
            let base = rust_type(&field.kind).expect("scalar or enum field");
            let ty = if field.optional {
                format!("Option<{base}>")
            } else {
                base
            };
            output.push_str(&format!("    pub {rust_name}: {ty},\n"));
        }
        output.push_str("}\n\n");
        let relations: Vec<_> = model
            .fields
            .iter()
            .filter(|field| matches!(field.kind, FieldType::Relation { .. }))
            .collect();
        if !relations.is_empty() {
            output.push_str("#[allow(dead_code)]\n");
            output.push_str(&format!("impl {} {{\n", model.name));
            for field in relations {
                let FieldType::Relation {
                    model: target,
                    many,
                } = &field.kind
                else {
                    unreachable!()
                };
                let constant = format!("RELATION_{}", field.name.to_snake_case().to_uppercase());
                output.push_str(&format!(
                    "    pub const {constant}: lite_orm::RelationMetadata = lite_orm::RelationMetadata {{\n        name: {:?},\n        target: {:?},\n        fields: &{:?},\n        references: &{:?},\n        many: {many},\n    }};\n",
                    field.name, target, field.relation_fields, field.relation_references
                ));
            }
            output.push_str("}\n\n");
        }
    }
    output.pop();
    output
}

fn rust_variant_name(name: &str) -> String {
    let mut s = name.to_upper_camel_case();
    if s.is_empty() {
        return "Empty".into();
    }
    if s.chars().next().unwrap().is_ascii_digit() {
        s = format!("V{s}");
    }
    match s.as_str() {
        "Self" => "Self_".into(),
        _ => s,
    }
}

fn rust_field_name(name: &str) -> String {
    let s = name.to_snake_case();
    match s.as_str() {
        "as" | "break" | "const" | "continue" | "crate" | "else" | "enum" | "extern" | "false"
        | "fn" | "for" | "if" | "impl" | "in" | "let" | "loop" | "match" | "mod" | "move"
        | "mut" | "pub" | "ref" | "return" | "self" | "Self" | "static" | "struct" | "super"
        | "trait" | "true" | "type" | "unsafe" | "use" | "where" | "while" | "async" | "await"
        | "dyn" | "abstract" | "become" | "box" | "do" | "final" | "macro" | "override"
        | "priv" | "typeof" | "unsized" | "virtual" | "yield" | "try" => format!("r#{s}"),
        _ => s,
    }
}

fn rust_type(kind: &FieldType) -> Option<String> {
    match kind {
        FieldType::Int32 => Some("i32".into()),
        FieldType::Int64 => Some("i64".into()),
        FieldType::Float => Some("f64".into()),
        FieldType::Boolean => Some("bool".into()),
        FieldType::String => Some("String".into()),
        FieldType::Bytes => Some("Vec<u8>".into()),
        FieldType::Json => Some("lite_orm::types::Json".into()),
        FieldType::Uuid => Some("lite_orm::types::Uuid".into()),
        FieldType::Date => Some("lite_orm::types::NaiveDate".into()),
        FieldType::Time => Some("lite_orm::types::NaiveTime".into()),
        FieldType::DateTime => Some("lite_orm::types::DateTime<lite_orm::types::Utc>".into()),
        FieldType::Enum(name) => Some(name.to_upper_camel_case()),
        FieldType::Array(inner) => Some(format!("Vec<{}>", rust_type(inner)?)),
        FieldType::Unsupported(_) => Some("String".into()),
        FieldType::Relation { .. } => None,
    }
}

#[cfg(test)]
mod tests {
    #[test]
    fn generates_rust_models() {
        let schema = crate::schema::parse(include_str!("../starter.schema")).unwrap();
        let output = super::rust(&schema);
        assert!(output.contains("pub struct User"));
        assert!(output.contains("pub created_at: lite_orm::types::DateTime"));
    }

    #[test]
    fn generates_rust_enums() {
        let schema = crate::schema::parse(
            r#"
            datasource db {
              provider = "postgresql"
              url = env("DATABASE_URL")
            }
            enum Gender {
              male
              female
            }
            struct User {
              id Int32 @id
              gender Gender?
            }
            "#,
        )
        .unwrap();
        let output = super::rust(&schema);
        assert!(output.contains("pub enum Gender"));
        assert!(output.contains("Male,"));
        assert!(output.contains("Female,"));
        assert!(output.contains("pub gender: Option<Gender>,"));
    }
}
