use std::fs;
use std::net::TcpListener;
use std::path::{Path, PathBuf};
use std::process::{Child, Command, Output, Stdio};
use std::thread;
use std::time::{Duration, SystemTime, UNIX_EPOCH};

struct TestServer {
    child: Child,
    root: PathBuf,
}

impl Drop for TestServer {
    fn drop(&mut self) {
        let _ = self.child.kill();
        let _ = self.child.wait();
        let _ = fs::remove_dir_all(&self.root);
    }
}

#[test]
fn concurrent_first_deployers_do_not_replay_a_migration() {
    if !available("initdb") || !available("postgres") || !available("pg_isready") {
        eprintln!("skipping PostgreSQL concurrency test: server tools are unavailable");
        return;
    }

    let unique = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .expect("system clock")
        .as_nanos();
    let root = std::env::temp_dir().join(format!(
        "liteorm-concurrent-{}-{unique}",
        std::process::id()
    ));
    let data = root.join("data");
    let project = root.join("project");
    fs::create_dir_all(project.join("migrations/0001_initial")).unwrap();

    assert_success(
        &Command::new("initdb")
            .args(["-D", path(&data), "-A", "trust", "-U", "postgres"])
            .output()
            .unwrap(),
    );

    let listener = TcpListener::bind("127.0.0.1:0").unwrap();
    let port = listener.local_addr().unwrap().port();
    drop(listener);
    let child = Command::new("postgres")
        .args([
            "-D",
            path(&data),
            "-h",
            "127.0.0.1",
            "-p",
            &port.to_string(),
            "-k",
            "/tmp",
        ])
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .unwrap();
    let _server = TestServer { child, root };

    let mut ready = false;
    for _ in 0..100 {
        if Command::new("pg_isready")
            .args(["-h", "127.0.0.1", "-p", &port.to_string()])
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status()
            .is_ok_and(|status| status.success())
        {
            ready = true;
            break;
        }
        thread::sleep(Duration::from_millis(50));
    }
    assert!(ready, "ephemeral PostgreSQL server did not become ready");

    fs::write(
        project.join("liteorm.schema"),
        r#"datasource db {
  provider = "postgresql"
  url = env("DATABASE_URL")
}

struct Item {
  id Int32 @id @default(autoincrement())
  @@map("items")
  @@schema("concurrency_test")
}
"#,
    )
    .unwrap();
    fs::write(
        project.join("migrations/0001_initial/migration.sql"),
        "CREATE TABLE concurrency_test.items (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);",
    )
    .unwrap();

    let url = format!("postgresql://postgres@127.0.0.1:{port}/postgres?sslmode=disable");
    let launch = || {
        let mut command = Command::new(env!("CARGO_BIN_EXE_liteorm"));
        command
            .current_dir(&project)
            .args(["migrate", "deploy"])
            .env("DATABASE_URL", &url)
            .env("DATABASE_URL_UNPOOLED", &url)
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .unwrap()
    };
    let first = launch();
    let second = launch();
    assert_success(&first.wait_with_output().unwrap());
    assert_success(&second.wait_with_output().unwrap());

    let output = Command::new("psql")
        .args([
            &url,
            "-Atc",
            "SELECT count(*) FROM concurrency_test._lite_orm_migrations",
        ])
        .output()
        .unwrap();
    assert_success(&output);
    assert_eq!(String::from_utf8(output.stdout).unwrap().trim(), "1");
}

fn available(program: &str) -> bool {
    Command::new(program)
        .arg("--version")
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .is_ok_and(|status| status.success())
}

fn path(path: &Path) -> &str {
    path.to_str().expect("test path must be UTF-8")
}

fn assert_success(output: &Output) {
    assert!(
        output.status.success(),
        "command failed\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}
